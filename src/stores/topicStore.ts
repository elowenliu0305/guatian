function makeNotes(topicId: string, contents: string[], startId: number): Note[] {
  const baseDate = new Date('2026-06-01').getTime()
  return contents.map((content, i) => ({
    id: `n${startId + i}`,
    topicId,
    x: 10 + (i % 7) * 180,
    y: 10 + Math.floor(i / 7) * 120,
    content,
    color: COLORS[i % COLORS.length],
    author: AUTHORS[i % AUTHORS.length],
    createdAt: new Date(baseDate - Math.random() * 7 * 86400000).toISOString(),
    updatedAt: new Date(baseDate - Math.random() * 7 * 86400000).toISOString(),
    likes: Math.floor(Math.random() * 80) + 1,
  }))
}

